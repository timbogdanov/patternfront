# ── conversion ───────────────────────────────────────────────────────────

def encode_of(w: int, h: int, scale: int, bits: list[int]) -> str:
    a, b = w - 2, h - 2
    raw = bytearray(3 + ((w * h + 7) >> 3))
    raw[0] = 0
    raw[1] = (scale & 0x07) | ((a & 0x1F) << 3)
    raw[2] = ((a >> 5) & 0x03) | ((b & 0x3F) << 2)
    for i, v in enumerate(bits):
        if v:
            raw[3 + (i >> 3)] |= 1 << (i & 7)
    return base64.urlsafe_b64encode(bytes(raw)).decode().rstrip("=")


def decode_of(data: str):
    by = base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))
    scale = by[1] & 0x07
    w = (((by[2] & 0x03) << 5) | ((by[1] >> 3) & 0x1F)) + 2
    h = ((by[2] >> 2) & 0x3F) + 2
    bits = [(by[3 + (i >> 3)] >> (i & 7)) & 1 for i in range(w * h)]
    return w, h, scale, bits


def write_png(path, width, height, rows):
    raw = b"".join(b"\x00" + bytes(r) for r in rows)

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data +
                struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    png = (b"\x89PNG\r\n\x1a\n" +
           chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)) +
           chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    open(path, "wb").write(png)


def main() -> int:
    kept, dropped = [], []

    for key, rows in S.items():
        widths = {len(r) for r in rows}
        if len(widths) != 1:
            dropped.append((key, f"ragged rows: {sorted(widths)}"))
            continue
        w, h = widths.pop(), len(rows)
        if w < 2 or h < 2 or w > 129 or h > 65:
            dropped.append((key, f"{w}x{h} outside the format"))
            continue
        bits = [1 if ch == "#" else 0 for r in rows for ch in r]
        ink = sum(bits) / len(bits)
        if not (MIN_INK <= ink <= MAX_INK):
            dropped.append((key, f"ink {ink:.0%} — reads as "
                                 f"{'empty' if ink < MIN_INK else 'a blob'}"))
            continue
        data = encode_of(w, h, 0, bits)
        rw, rh, _, rb = decode_of(data)
        if (rw, rh) != (w, h) or rb != bits:
            dropped.append((key, "round-trip mismatch"))
            continue
        kept.append((key, w, h, ink, data, bits))

    print(f"{'stamp':22}{'size':>8}{'ink':>7}{'chars':>7}")
    print("-" * 46)
    for key, w, h, ink, data, _ in kept:
        print(f"{key:22}{f'{w}x{h}':>8}{ink:>6.0%}{len(data):>7}")
    print("-" * 46)
    print(f"kept {len(kept)}   dropped {len(dropped)}")
    for key, why in dropped:
        print(f"  dropped {key}: {why}")

    # contact sheet at 4x with labels, for the human review step
    if kept:
        CELL, PADX, LBL = 4, 8, 8
        cols = 8
        cw = max(w for _, w, _, _, _, _ in kept) * CELL + PADX * 2
        ch = max(h for _, _, h, _, _, _ in kept) * CELL + PADX * 2 + LBL
        rows_n = (len(kept) + cols - 1) // cols
        W, H = cols * cw, rows_n * ch
        BG, INK, LB = (18, 18, 20), (235, 235, 240), (110, 110, 120)
        canvas = [bytearray(BG * W) for _ in range(H)]

        def put(x, y, c):
            if 0 <= x < W and 0 <= y < H:
                canvas[y][x * 3:x * 3 + 3] = bytes(c)

        FONT = {  # 3x5, enough for labels
            "A": [2, 5, 7, 5, 5], "B": [6, 5, 6, 5, 6], "C": [3, 4, 4, 4, 3],
            "D": [6, 5, 5, 5, 6], "E": [7, 4, 6, 4, 7], "F": [7, 4, 6, 4, 4],
            "G": [3, 4, 5, 5, 3], "H": [5, 5, 7, 5, 5], "I": [7, 2, 2, 2, 7],
            "J": [1, 1, 1, 5, 2], "K": [5, 5, 6, 5, 5], "L": [4, 4, 4, 4, 7],
            "M": [5, 7, 7, 5, 5], "N": [5, 7, 7, 7, 5], "O": [2, 5, 5, 5, 2],
            "P": [6, 5, 6, 4, 4], "Q": [2, 5, 5, 6, 3], "R": [6, 5, 6, 5, 5],
            "S": [3, 4, 2, 1, 6], "T": [7, 2, 2, 2, 2], "U": [5, 5, 5, 5, 7],
            "V": [5, 5, 5, 5, 2], "W": [5, 5, 7, 7, 5], "X": [5, 5, 2, 5, 5],
            "Y": [5, 5, 2, 2, 2], "Z": [7, 1, 2, 4, 7], "/": [1, 1, 2, 4, 4],
            " ": [0, 0, 0, 0, 0],
        }

        def text(x0, y0, s, c):
            for i, chn in enumerate(s.upper()[:20]):
                g = FONT.get(chn)
                if not g:
                    continue
                for r in range(5):
                    for col in range(3):
                        if (g[r] >> (2 - col)) & 1:
                            put(x0 + i * 4 + col, y0 + r, c)

        for idx, (key, w, h, ink, data, bits) in enumerate(kept):
            gx, gy = (idx % cols) * cw, (idx // cols) * ch
            for y in range(h):
                for x in range(w):
                    if bits[y * w + x]:
                        for py in range(CELL):
                            for px in range(CELL):
                                put(gx + PADX + x * CELL + px,
                                    gy + PADX + y * CELL + py, INK)
            text(gx + PADX, gy + ch - LBL, key.split("/")[1], LB)

        os.makedirs(os.path.dirname(SHEET), exist_ok=True)
        write_png(SHEET, W, H, canvas)
        print(f"\ncontact sheet: {SHEET}  ({W}x{H})")

    extra = import_openfront(argv_value("--openfront"))

    if "--emit" in sys.argv:
        print("\nconst STAMPS=[")
        for key, w, h, _, data, _ in kept:
            grp, nm = key.split("/")
            print(f"  ['{grp}','{nm}','{data}'],")
        for nm, data in extra:
            print(f"  ['game','{nm}','{data}'],")
        print("];")
        if extra:
            print(f"\n// {len(extra)} of the above are OpenFront's own patterns,")
            print("// CC BY-SA 4.0 — attribution to \"OpenFront LLC\" required if you")
            print("// redistribute them. See NOTICE.")

    return 0 if kept else 1


def argv_value(flag: str):
    """Value following `flag` on the command line, or None."""
    if flag in sys.argv:
        i = sys.argv.index(flag)
        if i + 1 < len(sys.argv):
            return sys.argv[i + 1]
    return None


def import_openfront(checkout):
    """
    Read the in-game patterns from a local OpenFront checkout.

    This project does not redistribute them — they are CC BY-SA 4.0 and some
    depict characters OpenFront cannot sublicense (see NOTICE). But the licence
    permits *you* to use them locally, so this reads them straight from your own
    clone and emits them alongside the authored set. Nothing is written into
    this repository.
    """
    if not checkout:
        return []
    import json
    src = os.path.join(os.path.expanduser(checkout),
                       "resources", "cosmetics", "cosmetics.json")
    if not os.path.exists(src):
        print(f"\n--openfront: no cosmetics.json at {src}")
        return []

    raw = json.load(open(src)).get("patterns", {})
    out = []
    for data, meta in sorted(raw.items(), key=lambda kv: kv[1].get("name", "")):
        name = meta.get("name") if isinstance(meta, dict) else None
        if not name:
            continue
        # Skip what should not be copied around even locally-by-default.
        if name.startswith("grogu"):
            continue
        out.append((name, data))

    print(f"\n--openfront: {len(out)} in-game patterns read from {checkout}")
    print("   CC BY-SA 4.0 · attribution \"OpenFront LLC\" · grogu patterns skipped")
    return out


