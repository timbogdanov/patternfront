"""
Author the PatternFront stamp library.

Shapes are written as ASCII art below so they can be reviewed and edited as
pictures rather than as hex. This script converts each to an OpenFront
`patternData` string — a stamp IS a small 1-bit pattern, so it reuses the codec
already verified against all 31 real game patterns instead of inventing a second
format.

It also refuses shapes that will not read at actual size: anything under 8% or
over 75% ink is either invisible or a blob. Everything that survives is drawn to
a contact sheet for a human to look at, which is the step that actually decides
what ships.

    python3 tools/gen-stamps.py            # report + contact sheet
    python3 tools/gen-stamps.py --emit     # also print the JS block
"""

